import fse from 'fs-extra'
import path from 'node:path'

const inputDirectory = path.resolve('../shoreline-ai/src/styles/components')
const outputFile = path.resolve('__styles__/shoreline-ai.css')

/**
 * The docs load the Shoreline theme without cascade layers, so the rules of
 * `@vtex/shoreline-ai/css`, which live inside `@layer sl-components`, lose to
 * the base rules of the components they restyle (for example the textarea).
 *
 * This script writes an unlayered copy of those styles: it removes the
 * `@layer sl-components { ... }` wrapper of every component file.
 */
function main() {
  const files = fse
    .readdirSync(inputDirectory)
    .filter((file) => file.endsWith('.css'))
    .sort()

  const css = files
    .map((file) => {
      const source = fse
        .readFileSync(`${inputDirectory}/${file}`, 'utf8')
        .trim()
      const match = source.match(/^@layer sl-components\s*\{([\s\S]*)\}$/)

      if (!match) {
        throw new Error(`${file}: expected a single @layer sl-components block`)
      }

      return `/* ${file} */\n${match[1].trim()}\n`
    })
    .join('\n')

  fse.outputFileSync(
    outputFile,
    `/* Autogenerated by scripts/build-ai-css.mjs. Do not edit. */\n\n${css}`
  )
  console.log('✅ Shoreline AI styles generated')
}

main()
