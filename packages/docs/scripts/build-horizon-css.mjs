import fse from 'fs-extra'
import path from 'node:path'

const themeDirectory = path.resolve('../shoreline/src/themes/horizon')
const outputFile = path.resolve('__styles__/horizon-scope.css')
const scope = "[data-sl-theme='horizon']"

/**
 * The docs load the Sunrise theme for the whole document, and a theme declares
 * its tokens on `:root`. The Shoreline AI components are designed for Horizon,
 * so their previews need Horizon without changing the rest of the site.
 *
 * This script writes a copy of the Horizon theme scoped to
 * `[data-sl-theme='horizon']`: the full token set, declared on the scope
 * element, and the Horizon component overrides, nested under it. The shared
 * component rules already loaded with Sunrise then resolve the Horizon tokens
 * inside the scope.
 *
 * Content rendered in a portal leaves the scope and keeps the Sunrise tokens.
 */
function main() {
  const tokens = fse.readFileSync(`${themeDirectory}/tokens.css`, 'utf8')

  if ((tokens.match(/^:root\s*\{/gm) ?? []).length !== 1) {
    throw new Error('tokens.css: expected a single :root block')
  }

  const scopedTokens = tokens.replace(/^:root\s*\{/m, `${scope} {`)

  const index = fse.readFileSync(
    `${themeDirectory}/components/index.css`,
    'utf8'
  )
  const overrides = [...index.matchAll(/@import\s+"([^"]+)";/g)]
    .map((match) => match[1])
    .filter((file) => !file.startsWith('../'))
    .map((file) => {
      const source = fse.readFileSync(
        `${themeDirectory}/components/${file}`,
        'utf8'
      )

      if (/@import|@layer|:root/.test(source)) {
        throw new Error(`${file}: expected plain component rules`)
      }

      return `/* ${file} */\n${source.trim()}`
    })
    .join('\n\n')

  fse.outputFileSync(
    outputFile,
    [
      '/* Autogenerated by scripts/build-horizon-css.mjs. Do not edit. */',
      scopedTokens.trim(),
      `${scope} {\n  color: var(--sl-fg-base);\n\n${overrides}\n}`,
      '',
    ].join('\n\n')
  )
  console.log('✅ Scoped Horizon theme generated')
}

main()
