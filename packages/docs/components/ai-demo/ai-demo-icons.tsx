/**
 * The app's thumbs, as the proposal draws them: an outline glyph, and a
 * filled glyph (same color) when the action is pressed. The selected
 * thumbs-down is the selected thumbs-up mirrored, as the outline pair is.
 */
export function ThumbIcon(props: {
  direction: 'up' | 'down'
  selected?: boolean
}) {
  const { direction, selected = false } = props

  if (selected) {
    return (
      <svg
        width="20"
        height="20"
        viewBox="0 0 16 16"
        fill="none"
        aria-hidden="true"
        focusable="false"
        style={direction === 'down' ? { transform: 'scaleY(-1)' } : undefined}
      >
        {THUMB_SELECTED_PATHS.map((d) => (
          <path key={d} d={d} fill="currentColor" />
        ))}
      </svg>
    )
  }

  return (
    <svg
      width="20"
      height="20"
      viewBox="0 0 20 20"
      fill="none"
      aria-hidden="true"
      focusable="false"
    >
      <path
        fillRule="evenodd"
        clipRule="evenodd"
        d={direction === 'up' ? THUMB_UP_PATH : THUMB_DOWN_PATH}
        fill="currentColor"
      />
    </svg>
  )
}
